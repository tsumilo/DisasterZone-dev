"""Generates DisasterZone Data/BiSLists.lua: ns.Data.BiSLists = { [guide] = { [phase] = "slot:item[*],..." } }, the
suggested BiS lists per class guide and phase (1..5) that My BiS > Suggest fills a list from (Core/Loon.lua).

Source: the guide files of the installed LoonBestInSlot addon (Guides/<Class><Spec>.lua, which name wowhead's TBC
class guides as their own source). Only the item lines are taken: item id, slot and whether the guide ranks it "BIS";
gems, enchants and the pre-raid lists (phase 0) are left out. The order of a guide's lines is kept (it is the guide's
priority order).

Run: python generators/gen_bis_lists.py [--write]     (without --write: the report only)
"""
import os
import re
import sys

ADDON = r"C:\World of Warcraft\_anniversary_\Interface\AddOns\DisasterZone"
LOON = r"C:\World of Warcraft\_anniversary_\Interface\AddOns\LoonBestInSlot"
OUT = os.path.join(ADDON, "Data", "BiSLists.lua")

# The slot numbers of the data strings (Core/Loon.lua has the same list).
SLOTS = ["Head", "Neck", "Shoulder", "Back", "Chest", "Wrist", "Hands", "Waist", "Legs", "Feet",
         "Ring", "Trinket", "Main Hand", "Off Hand", "Two Hand", "Ranged/Relic"]
SLOT_NO = {name: i + 1 for i, name in enumerate(SLOTS)}
PHASES = range(1, 6)
MAX_ITEM_ID = 200000

RE_LOADER = re.compile(r"^function LBIS:Load(\w+)\(\)")
RE_SPEC = re.compile(r'^\s*local (\w+) = LBIS:RegisterSpec\([^,]+,[^,]+,\s*"(\d+)"')
RE_ITEM = re.compile(r'^\s*LBIS:AddItem\((\w+),\s*"(\d+)",\s*LBIS\.L\["([^"]+)"\],\s*"([^"]*)"\)')


def parse(path):
    """-> guide name, { phase: [ (slot number, item id, is BIS) ] }, skipped lines"""
    name, specs, lists, skipped = None, {}, {}, []
    with open(path, encoding="utf-8", errors="replace") as fh:
        for line in fh:
            m = RE_LOADER.match(line)
            if m:
                if name:
                    raise SystemExit("%s: more than one loader" % path)
                name = m.group(1)
                continue
            m = RE_SPEC.match(line)
            if m:
                specs[m.group(1)] = int(m.group(2))
                continue
            if "LBIS:AddItem(" not in line:
                continue
            m = RE_ITEM.match(line)
            if not m or m.group(1) not in specs:
                raise SystemExit("%s: unreadable item line: %s" % (path, line.strip()))
            phase, item, slot, rank = specs[m.group(1)], int(m.group(2)), m.group(3), m.group(4)
            if phase not in PHASES:
                continue
            if slot not in SLOT_NO or not (1 <= item <= MAX_ITEM_ID):
                skipped.append((phase, slot, item))
                continue
            entry = (SLOT_NO[slot], item, rank.upper().startswith("BIS"))
            rows = lists.setdefault(phase, [])
            if entry[:2] not in [r[:2] for r in rows]:
                rows.append(entry)
    if not name:
        raise SystemExit("%s: no loader" % path)
    return name, lists, skipped


def main():
    write = "--write" in sys.argv
    with open(os.path.join(LOON, "LoonBestInSlot.toc"), encoding="utf-8") as fh:
        version = re.search(r"## Version:\s*(\S+)", fh.read()).group(1)
    guides, total, skipped = {}, 0, []
    gdir = os.path.join(LOON, "Guides")
    for fn in sorted(os.listdir(gdir)):
        if fn.endswith(".lua"):
            name, lists, skip = parse(os.path.join(gdir, fn))
            guides[name] = lists
            total += sum(len(v) for v in lists.values())
            skipped += [(name,) + s for s in skip]
    out = [
        'if DisasterZoneBoot and DisasterZoneBoot.Run("Data/BiSLists.lua", ...) then return end -- DisasterZone '
        "suggested BiS lists per class guide and phase (My BiS > Suggest).",
        "-- AUTO-GENERATED by gen_bis_lists.py - do not edit by hand; re-run the generator instead.",
        "-- Source: the guide files of LoonBestInSlot %s (Guides/*.lua; they name wowhead's TBC class guides as their"
        % version,
        "-- source). Item ids, slots and the guides' BIS marks only; no gems, enchants or pre-raid lists.",
        '-- [guide] = { [phase 1..5] = "slot:item,..." } in the guide\'s priority order; * = the guide ranks it BIS.',
        "-- Slots: " + ", ".join("%d %s" % (i + 1, s) for i, s in enumerate(SLOTS)) + ".",
        "local addonName, ns = ...",
        "ns.Data = ns.Data or {}",
        "",
        "ns.Data.BiSLists = {",
    ]
    for name in sorted(guides):
        out.append("  %s = {" % name)
        for phase in PHASES:
            rows = guides[name].get(phase)
            if rows:
                out.append('    [%d] = "%s",' % (phase, ",".join("%d:%d%s" % (s, i, "*" if b else "") for s, i, b in rows)))
        out.append("  },")
    out.append("}")
    out.append("")
    text = "\n".join(out)
    print("%d guides, %d entries, %d bytes; %d lines skipped (slot not used by DisasterZone)" % (
        len(guides), total, len(text), len(skipped)))
    for s in skipped:
        print("  skipped: %s P%d %s %d" % s)
    if write:
        with open(OUT, "w", encoding="utf-8", newline="\n") as fh:
            fh.write(text)
        print("wrote", OUT)


if __name__ == "__main__":
    main()
