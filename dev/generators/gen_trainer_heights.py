"""Raid Trainer: the real floor heights of an encounter's room, from Blizzard's building geometry (WMO group files).

Teron Gorefiend's hall is group 31 of world/wmo/dungeon/blacktemple/blacktemple.wmo (file 108745, WMOGroupID 22426,
"Gorefiend's Vigil"); files are fetched from wago.tools into dev/art/wmo/ (git-ignored, Blizzard's data).
The hall's floor spans local x -675..-615 and y -817..-759; the entrance corridor leaves on the +y side, which is
south on Blizzard's map, so the room is turned half round: arena x = -615 - local x, arena y = -759 - local y.

Writes Games/Trainer/Encounters/TeronGorefiendFloor.lua: one letter per square yard, 'A' + (height + 2.5) / 0.25,
height 0 = the hall's main floor (local z 371.5).

Run: luaenv\\Scripts\\python.exe generators\\gen_trainer_heights.py
"""
import math
import os
import urllib.request

import wmo_tools as W

HERE = os.path.dirname(os.path.abspath(__file__))
ART = os.path.join(HERE, "..", "art", "wmo")
OUT = os.path.join(HERE, "..", "..", "addon", "DisasterZone", "Games", "Trainer", "Encounters", "TeronGorefiendFloor.lua")

GROUP_FILE = 108745
X_EAST, Y_SOUTH, Z_MAIN = -615.0, -759.0, 371.5
W_YD, H_YD = 60, 58
BASE, STEP, TOP = -2.5, 0.25, 2.0


def fetch(fdid):
    path = os.path.join(ART, "%d.wmo" % fdid)
    if not os.path.exists(path) or os.path.getsize(path) == 0:
        os.makedirs(ART, exist_ok=True)
        req = urllib.request.Request("https://wago.tools/api/casc/%d?download" % fdid, headers={"User-Agent": "Mozilla/5.0"})
        open(path, "wb").write(urllib.request.urlopen(req, timeout=120).read())
    return path


def floor_tris(group):
    out = []
    for t in group["tris"]:
        a, b, c = [group["verts"][i] for i in t]
        ux, uy, uz = b[0] - a[0], b[1] - a[1], b[2] - a[2]
        vx, vy, vz = c[0] - a[0], c[1] - a[1], c[2] - a[2]
        nx, ny, nz = uy * vz - uz * vy, uz * vx - ux * vz, ux * vy - uy * vx
        ln = math.sqrt(nx * nx + ny * ny + nz * nz)
        # faces you can stand on, below head height over the main floor (not the ceiling)
        if ln > 1e-6 and abs(nz) / ln > 0.5 and max(a[2], b[2], c[2]) < Z_MAIN + 4.5:
            out.append((a, b, c))
    return out


def height_at(tris, x, y):
    best = None
    for a, b, c in tris:
        d = (b[1] - c[1]) * (a[0] - c[0]) + (c[0] - b[0]) * (a[1] - c[1])
        if abs(d) < 1e-9:
            continue
        w1 = ((b[1] - c[1]) * (x - c[0]) + (c[0] - b[0]) * (y - c[1])) / d
        w2 = ((c[1] - a[1]) * (x - c[0]) + (a[0] - c[0]) * (y - c[1])) / d
        w3 = 1 - w1 - w2
        if w1 >= -1e-4 and w2 >= -1e-4 and w3 >= -1e-4:
            z = w1 * a[2] + w2 * b[2] + w3 * c[2]
            if best is None or z > best:
                best = z
    return best


def main():
    tris = floor_tris(W.read_group(fetch(GROUP_FILE)))
    rows, lo, hi = [], 99, -99
    for j in range(H_YD):                      # south to north
        row = ""
        for i in range(W_YD):                  # west to east
            z = height_at(tris, X_EAST - (i + 0.5), Y_SOUTH - (j + 0.5))
            h = 0.0 if z is None else max(BASE, min(TOP, z - Z_MAIN))
            lo, hi = min(lo, h), max(hi, h)
            row += chr(ord("A") + int(round((h - BASE) / STEP)))
        rows.append(row)
    lines = [
        'if DisasterZoneBoot and DisasterZoneBoot.Run("Games/Trainer/Encounters/TeronGorefiendFloor.lua", ...) then return end -- DisasterZone Games/Trainer/Encounters/TeronGorefiendFloor.lua',
        "-- The floor heights of Teron Gorefiend's hall, one letter per square yard, rows south to north, west to east:",
        "-- height = (letter - 'A') * step + base, 0 = the main floor. Measured from Blizzard's own geometry of the room",
        "-- (blacktemple.wmo, group \"Gorefiend's Vigil\").",
        "-- AUTO-GENERATED by gen_trainer_heights.py; do not edit by hand.",
        "local _, ns = ...",
        "ns.TrainerFloors = ns.TrainerFloors or {}",
        "ns.TrainerFloors.teron = { w = %d, h = %d, base = %s, step = %s, rows = {" % (W_YD, H_YD, BASE, STEP),
    ]
    lines += ['  "%s",' % r for r in rows]
    lines += ["} }", ""]
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(lines))
    print("wrote %s: %d x %d, heights %.2f .. %.2f" % (os.path.normpath(OUT), W_YD, H_YD, lo, hi))
    for r in reversed(rows[::2]):
        print("  " + r[::1])


main()
