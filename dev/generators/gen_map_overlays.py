"""The world map's explored-area art for Guild > Map (2026-10-08). A zone's map art is a plain base layer, and the
game draws the areas the player has explored on top of it (WorldMapOverlay + WorldMapOverlayTile). The client only
says which ones *I* explored (C_MapExplorationInfo.GetExploredMapTextures), but guildmates stand in places I may never
have been, so the guild map draws every area, as if all were explored.

Tables from wago.tools for the installed build (2.5.6.69795), cached in dev/art/rooms/db2/. Writes
addon/DisasterZone/Data/MapOverlays.lua:
  ns.Data.MapOverlays[uiMapID] = { "width:height:offsetX:offsetY:fileID,fileID,...", ... }
(pixels of the map's art layer; the files row by row, 256px tiles, as Blizzard's MapExplorationDataProvider lays them)
Run from dev: luaenv\\Scripts\\python.exe generators\\gen_map_overlays.py
"""
import csv
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import gen_rooms as R  # noqa: E402

DEV = os.path.dirname(HERE)
CACHE = os.path.join(DEV, "art", "rooms", "db2")
WAGO = "https://wago.tools/db2/%s/csv?build=2.5.6.69795"
OUT = os.path.join(DEV, "..", "addon", "DisasterZone", "Data", "MapOverlays.lua")


def table(name):
    os.makedirs(CACHE, exist_ok=True)
    path = R._get(WAGO % name, os.path.join(CACHE, name + ".csv"))
    return list(csv.DictReader(open(path, encoding="utf-8")))


def main():
    maps_of_art = {}
    for r in table("UiMapXMapArt"):
        if int(r["PhaseID"] or 0) == 0:
            maps_of_art.setdefault(int(r["UiMapArtID"]), []).append(int(r["UiMapID"]))
    tiles = {}
    for r in table("WorldMapOverlayTile"):
        if int(r["LayerIndex"] or 0) == 0:
            tiles.setdefault(int(r["WorldMapOverlayID"]), []).append((int(r["RowIndex"]), int(r["ColIndex"]),
                                                                     int(r["FileDataID"])))
    out = {}
    for r in table("WorldMapOverlay"):
        oid = int(r["ID"])
        t = sorted(tiles.get(oid, []))
        if not t:
            continue
        w, h, x, y = (int(r[k]) for k in ("TextureWidth", "TextureHeight", "OffsetX", "OffsetY"))
        if w <= 0 or h <= 0:
            continue
        entry = "%d:%d:%d:%d:%s" % (w, h, x, y, ",".join(str(f) for _, _, f in t))
        for m in maps_of_art.get(int(r["UiMapArtID"]), []):
            out.setdefault(m, []).append((oid, entry))
    lines = ['if DisasterZoneBoot and DisasterZoneBoot.Run("Data/MapOverlays.lua", ...) then return end -- DisasterZone: '
             "the world map's explored-area art by uiMapID (Guild > Map draws them all)",
             "-- AUTO-GENERATED by gen_map_overlays.py from WorldMapOverlay / WorldMapOverlayTile (build 2.5.6.69795); "
             "do not edit by hand.",
             "-- [uiMapID] = { \"width:height:offsetX:offsetY:fileID,...\" } (art layer pixels; 256px tiles, row by row)",
             "local _, ns = ...",
             "ns.Data = ns.Data or {}",
             "ns.Data.MapOverlays = {"]
    n = 0
    for m in sorted(out):
        items = [e for _, e in sorted(out[m])]
        n += len(items)
        lines.append("    [%d] = { %s }," % (m, ", ".join('"%s"' % e for e in items)))
    lines.append("}")
    data = "\n".join(lines) + "\n"
    with open(OUT, "wb") as f:
        f.write(data.encode("utf-8"))
    print(OUT, len(out), "maps,", n, "overlays,", len(data) // 1024, "KB")


if __name__ == "__main__":
    main()
