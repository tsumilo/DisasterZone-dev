"""Boss portraits for the raid page's Assignments tab (2026-10-08): the Encounter Journal's boss pictures
(Interface/EncounterJournal/UI-EJ-BOSS-<Name>.blp, 128x64), which the Anniversary client ships in its CASC although it
has no journal. Looked up by name (the encounter's creatures of Data/BossPortraits.lua, then ALIASES) and stored by
file data ID, so the addon sets them with SetTexture(fileID).

Writes addon/DisasterZone/Data/BossJournal.lua:
  ns.Data.BossJournal["<Raid>:<Boss>"] = fileDataID
Run from dev: luaenv\\Scripts\\python.exe generators\\gen_boss_journal.py
"""
import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import casc_local as C  # noqa: E402

ADDON = os.path.join(HERE, "..", "..", "addon", "DisasterZone")
SRC = os.path.join(ADDON, "Data", "BossPortraits.lua")
OUT = os.path.join(ADDON, "Data", "BossJournal.lua")

# encounters whose journal picture has another name than any of their creatures
ALIASES = {
    # (the three beasts of the Servants' Quarters share its picture; the Opera, Chess, Zul'jin and the world bosses
    # have none in this client: the page falls back to the creature's portrait)
    "Karazhan:Rokad": ["Servant Quarters"],
    "Karazhan:Shadikith": ["Servant Quarters"],
    "Karazhan:Hyakiss": ["Servant Quarters"],
    "Karazhan:Chess": ["Chess Event", "The Chess Event"],
    "SerpentshrineCavern:Karathress": ["Fathom Lord Karathress"],
    "TempestKeep:Kaelthas": ["Kael'thas Sunstrider", "Kaelthas Sunstrider"],
    "TempestKeep:Alar": ["Al'ar", "Alar"],
    "BlackTemple:Council": ["The Illidari Council", "Illidari Council"],
    "BlackTemple:Reliquary": ["Reliquary of Souls", "Essence of Suffering"],
    "BlackTemple:Bloodboil": ["Gurtogg Bloodboil"],
    "SunwellPlateau:EredarTwins": ["The Eredar Twins", "Eredar Twins", "Grand Warlock Alythess", "Lady Sacrolash"],
    "SunwellPlateau:Muru": ["M'uru", "Muru"],
    "SunwellPlateau:Kiljaeden": ["Kil'jaeden", "Kiljaeden"],
    "ZulAman:Janalai": ["Jan'alai", "Janalai"],
    "ZulAman:Zuljin": ["Zul'jin", "Zuljin"],
    "ZulAman:Akilzon": ["Akil'zon", "Akilzon"],
    "ZulAman:Halazzi": ["Halazzi"],
    "ZulAman:Malacrass": ["Hex Lord Malacrass"],
}


def lookup(name):
    for n in (name, name.replace("-", " "), name.replace("'", "")):
        f = C.fdid_of("Interface/EncounterJournal/UI-EJ-BOSS-%s.blp" % n)
        if f and f in C.root():
            return f
    return None


def main():
    src = open(SRC, "rb").read().decode("utf-8")
    out, missing = {}, []
    for key, body in re.findall(r'\["([^"]+)"\] = \{(.*)\},?\s*$', src, re.M):
        names = ALIASES.get(key, []) + re.findall(r'n = "([^"]+)"', body)
        fid = None
        for n in names:
            fid = lookup(n)
            if fid:
                break
        if fid:
            out[key] = fid
        else:
            missing.append(key)
    lines = [
        'if DisasterZoneBoot and DisasterZoneBoot.Run("Data/BossJournal.lua", ...) then return end -- DisasterZone: '
        "the Encounter Journal's boss pictures (128x64) by encounter, as file data IDs",
        "-- AUTO-GENERATED by gen_boss_journal.py from the client's CASC; do not edit by hand.",
        "local _, ns = ...",
        "ns.Data = ns.Data or {}",
        "ns.Data.BossJournal = {",
    ]
    for key in sorted(out):
        lines.append('  ["%s"] = %d,' % (key, out[key]))
    lines.append("}")
    open(OUT, "wb").write(("\n".join(lines) + "\n").encode("utf-8"))
    print("%d encounters, %d without a picture: %s" % (len(out), len(missing), ", ".join(missing)))


if __name__ == "__main__":
    main()
