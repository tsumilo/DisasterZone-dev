"""Boss portraits for the strategy boards (Addendum K): creature display IDs per raid boss.

Reads the local AtlasLootClassic_DungeonsAndRaids/data-tbc.lua (npcID + DisplayIDs per encounter, GPL v2 like the
item data) and matches its encounters to CDLoot's bosses (Data/Items.lua) by creature ID. Writes
addon/CDLoot/Data/BossPortraits.lua: ns.Data.BossPortraits["<Raid>:<Boss>"] = { displayID, ... }.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
ADDON = os.path.join(HERE, "..", "..", "addon", "CDLoot")
ATLAS = os.path.join(r"C:\World of Warcraft\_anniversary_\Interface\AddOns", "AtlasLootClassic_DungeonsAndRaids", "data-tbc.lua")
OUT = os.path.join(ADDON, "Data", "BossPortraits.lua")


def nums(s):
    return [int(x) for x in re.findall(r"\d+", s)]


def main():
    items = open(os.path.join(ADDON, "Data", "Items.lua"), encoding="utf-8").read()
    bosses = []   # (ref, name, npcs)
    raid = None
    for line in items.splitlines():
        m = re.match(r'^  \{ key = "(\w+)"', line)
        if m:
            raid = m.group(1)
            continue
        m = re.match(r'^    \{ key = "(\w+)", name = "([^"]*)", npcIDs = \{([^}]*)\}', line)
        if m and raid:
            bosses.append(("%s:%s" % (raid, m.group(1)), m.group(2), set(nums(m.group(3)))))
    atlas = open(ATLAS, encoding="utf-8").read()
    enc = []      # (npcs, displayIDs)
    for m in re.finditer(r"npcID\s*=\s*(\{[^}]*\}|\d+)\s*,(.{0,200}?)DisplayIDs\s*=\s*\{((?:\{[^}]*\},?\s*)+)\}", atlas, re.S):
        disp = [nums(g)[0] for g in re.findall(r"\{([^}]*)\}", m.group(3)) if nums(g)]
        enc.append((set(nums(m.group(1))), disp))
    out, missing = {}, []
    for ref, name, npcs in bosses:
        for e_npcs, disp in enc:
            if npcs & e_npcs and disp:
                out[ref] = disp
                break
        else:
            missing.append(ref)
    lines = [
        "-- CDLoot: boss portraits for the strategy boards (creature display IDs per boss).",
        "-- AUTO-GENERATED by gen_boss_portraits.py from AtlasLootClassic_DungeonsAndRaids/data-tbc.lua (GPL v2);",
        "-- do not edit by hand.",
        "local _, ns = ...",
        "ns.Data = ns.Data or {}",
        "ns.Data.BossPortraits = {",
    ]
    for ref, _, _ in bosses:
        if ref in out:
            lines.append('  ["%s"] = { %s },' % (ref, ", ".join(str(x) for x in out[ref])))
    lines.append("}")
    open(OUT, "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
    print("bosses with portraits: %d, without: %s" % (len(out), ", ".join(missing)))


if __name__ == "__main__":
    main()
