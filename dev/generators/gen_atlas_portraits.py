#!/usr/bin/env python3
"""
Generator for Data/AtlasPortraits.lua: the Encounter Journal boss portrait (UI-EJ-BOSS-<name>, 128 x 64) of every raid
and dungeon page the Atlas lists, as FileDataIDs, for the Atlas's boss heroes, boss picker and section headers. The
TBC Anniversary client ships the modern Encounter Journal art but no API to find it, so the names are looked up in
the installed client's CASC here (dev/generators/casc_local.py) and the hits written out; a boss without one shows
UI-EJ-BOSS-Default in the addon.

Reads: <ADDON>/Data/Items.lua, Data/Dungeons.lua, Data/AtlasClassic.lua (page names, `name = "..."`).
Writes: <ADDON>/Data/AtlasPortraits.lua
Run from dev: luaenv\\Scripts\\python.exe generators\\gen_atlas_portraits.py
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
import casc_local as C  # noqa: E402

ADDON = HERE.parents[1] / "addon" / "DisasterZone"
SOURCES = ["Data/Items.lua", "Data/Dungeons.lua", "Data/AtlasClassic.lua"]
OUT = ADDON / "Data" / "AtlasPortraits.lua"
EJ = "Interface/EncounterJournal/UI-EJ-BOSS-%s.blp"


def variants(name):
    """The names the Journal may file a boss under: as written, without "The", without a bracket, either half of
    "A & B" / "A and B", without an epithet after a comma."""
    out = [name]
    base = re.sub(r"\s*\(.*\)$", "", name)
    out.append(base)
    out.append(re.sub(r"^The ", "", base))
    for sep in (" & ", " and ", " / "):
        if sep in base:
            out.extend(p.strip() for p in base.split(sep))
    out.append(base.split(",")[0])
    seen, uniq = set(), []
    for v in out:
        if v and v not in seen:
            seen.add(v)
            uniq.append(v)
    return uniq


def main():
    names = []
    for rel in SOURCES:
        text = (ADDON / rel).read_text(encoding="utf-8", errors="replace")
        for m in re.finditer(r'name = "((?:[^"\\]|\\.)+)"', text):
            n = m.group(1).replace('\\"', '"')
            if n not in names:
                names.append(n)
    found = {}
    for n in names:
        for v in variants(n):
            fid = C.fdid_of(EJ % v)
            if fid:
                found[n] = fid
                break
    default = C.fdid_of(EJ % "Default")
    lines = [
        'if DisasterZoneBoot and DisasterZoneBoot.Run("Data/AtlasPortraits.lua", ...) then return end -- DisasterZone '
        "Atlas boss portraits",
        "-- AUTO-GENERATED by gen_atlas_portraits.py - do not edit by hand; re-run the generator instead.",
        "-- ns.Data.AtlasPortraits[page name] = the FileDataID of its Encounter Journal portrait (UI-EJ-BOSS-*, 128 x 64);",
        "-- DEFAULT = the Journal's own stand-in for a boss without one.",
        "local _, ns = ...",
        "ns.Data = ns.Data or {}",
        "",
        "ns.Data.AtlasPortraits = {",
        "  DEFAULT = %d," % default,
    ]
    for n in sorted(found):
        lines.append('  ["%s"] = %d,' % (n.replace('"', '\\"'), found[n]))
    lines.append("}")
    OUT.write_bytes(("\n".join(lines) + "\n").encode("utf-8"))
    print("%d of %d names have a portrait -> %s" % (len(found), len(names), OUT))


if __name__ == "__main__":
    main()
