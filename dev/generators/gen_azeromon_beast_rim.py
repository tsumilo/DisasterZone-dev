"""The outline of every pixel beast's idle frames, for the rim light in battle (Azeromon 0.45, BattleScene.lua).

A rim lights the edge of a beast that faces a lamp, the low sun or the moon. The game cannot read pixels, so this
writes, per idle frame, where the body ends: each row's leftmost and rightmost opaque pixel and each column's
topmost one (the outline a rim light can reach). Read from the shipped pages (Media/Beasts/*.blp, palette + 1-bit
alpha) at the rectangles BeastArt.lua names, so it always matches what the game draws.

Output: addon/DisasterZone_Azeromon/BeastRim.lua
  ns.AzeroBeastRim = { asset, src, beasts = { [key] = { f = "<frame>|<frame>..", a = ".." } } }
  a frame = its rows' left ends, its rows' right ends, its columns' tops, each list a run of values:
    "!" + two base-64 characters = a value (absolute), one base-64 character = the change from the last value
    (-32 .. 31), "." = an empty row / column (the run starts again with "!").

Run: luaenv\\Scripts\\python.exe generators\\gen_azeromon_beast_rim.py
"""
import hashlib
import os
import re
import struct

import numpy as np

HERE = os.path.dirname(os.path.abspath(__file__))
DEV = os.path.dirname(HERE)
PACK = os.path.join(os.path.dirname(DEV), "addon", "DisasterZone_Azeromon")
ART = os.path.join(PACK, "BeastArt.lua")
PAGES = os.path.join(PACK, "Media", "Beasts")
OUT = os.path.join(PACK, "BeastRim.lua")
ASSET = 17
B64 = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"


def page_alpha(name, cache={}):
    """a page's alpha plane as a bool array (palette BLP2, 1-bit alpha low bit first)"""
    if name not in cache:
        with open(os.path.join(PAGES, name + ".blp"), "rb") as f:
            d = f.read()
        assert d[:4] == b"BLP2" and d[8] == 1 and d[9] == 1, name
        w, h = struct.unpack_from("<II", d, 12)
        off = struct.unpack_from("<I", d, 20)[0]
        bits = np.frombuffer(d, dtype=np.uint8, count=(w * h + 7) // 8, offset=off + w * h)
        cache[name] = np.unpackbits(bits, bitorder="little")[:w * h].reshape(h, w).astype(bool)
    return cache[name]


def beasts():
    """key -> (page, { "f": idle frames, "a": idle frames }) from BeastArt.lua; a frame = (x, y, w, h)"""
    src = open(ART, encoding="utf-8").read()
    out = {}
    for m in re.finditer(r'\["([^"]+)"\] = \{ tex = "(\w+)"[^\n]*\n\s*f = "([^"]*)",\s*\n\s*a = "([^"]*)"', src):
        key, tex, f, a = m.groups()
        views = {}
        for v, s in (("f", f), ("a", a)):
            im = re.search(r"(?:^|;)idle=\d:([-\d,]*)", s)
            nums = [int(n) for n in im.group(1).split(",")] if im and im.group(1) else []
            views[v] = [tuple(nums[i:i + 4]) for i in range(0, len(nums), 6)]
        out[key] = (tex, views)
    return out


def run(values):
    """a list of ints (-1 = empty) as the run encoding"""
    out, last = [], None
    for v in values:
        if v < 0:
            out.append(".")
            last = None
        elif last is not None and -32 <= v - last <= 31:
            out.append(B64[v - last + 32])
            last = v
        else:
            out.append("!" + B64[v & 63] + B64[v >> 6])
            last = v
    return "".join(out)


def outline(a):
    """rows' left / right ends and columns' tops of a frame's alpha (-1 where empty)"""
    h, w = a.shape
    left, right, top = [], [], []
    for y in range(h):
        xs = np.flatnonzero(a[y])
        left.append(int(xs[0]) if len(xs) else -1)
        right.append(int(xs[-1]) if len(xs) else -1)
    for x in range(w):
        ys = np.flatnonzero(a[:, x])
        top.append(int(ys[0]) if len(ys) else -1)
    return left, right, top


def main():
    data = beasts()
    lines = []
    digest = hashlib.sha1(open(ART, "rb").read().replace(b"\r\n", b"\n"))
    for key in sorted(data):
        tex, views = data[key]
        pa = page_alpha(tex)
        parts = []
        for v in ("f", "a"):
            frames = []
            for x, y, w, h in views[v]:
                left, right, top = outline(pa[y:y + h, x:x + w])
                frames.append(run(left) + "," + run(right) + "," + run(top))
            parts.append('%s = "%s"' % (v, "|".join(frames)))
        lines.append('        ["%s"] = { %s },' % (key, ", ".join(parts)))
    head = [
        'if DisasterZoneBoot and DisasterZoneBoot.Run("DisasterZone_Azeromon/BeastRim.lua", ...) then return end '
        "-- DisasterZone_Azeromon/BeastRim.lua  (GENERATED by dev/generators/gen_azeromon_beast_rim.py - do not edit)",
        "-- Where each pixel beast's idle frames end (for the rim light in battle, BattleScene.lua): per frame its rows'",
        "-- left ends, rows' right ends and columns' tops, comma-separated runs: \"!\" + two base-64 characters = a value,",
        "-- one character = the change from the last (-32 .. 31), \".\" = empty. Frames in the idle clip's order.",
        "local addonName, ns = ...",
        "ns.AzeroBeastRim = {",
        '    asset = %d, src = "%s",' % (ASSET, digest.hexdigest()[:16]),
        "    beasts = {",
    ]
    with open(OUT, "w", newline="\n", encoding="utf-8") as f:
        f.write("\n".join(head + lines + ["    },", "}"]) + "\n")
    print("wrote BeastRim.lua", len(lines), "beasts", os.path.getsize(OUT), "bytes")


if __name__ == "__main__":
    main()
