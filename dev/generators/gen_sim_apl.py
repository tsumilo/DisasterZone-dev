"""Generate Data/SimAPL.lua: WoWSims' rotations (action priority lists) as Lua tables for Sim/APL.lua.

Source: WoWSims TBC (dev/ext/wowsims-tbc, MIT) ui/specs/<class>/<spec>/apls/<name>.apl.json, unchanged.
Usage: python gen_sim_apl.py
"""
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
DEV = os.path.normpath(os.path.join(HERE, ".."))
WOWSIMS = os.path.join(DEV, "ext", "wowsims-tbc")
OUT = os.path.normpath(os.path.join(DEV, "..", "addon", "DisasterZone", "Data", "SimAPL.lua"))

# key -> WoWSims APL file
APLS = {
    "PALADIN:Retribution": "ui/specs/paladin/retribution/apls/default.apl.json",
    "WARRIOR:Fury": "ui/specs/warrior/dps/apls/fury.apl.json",
    "WARRIOR:Arms": "ui/specs/warrior/dps/apls/arms.apl.json",
    "SHAMAN:Enhancement": "ui/specs/shaman/enhancement/apls/default.apl.json",
    "SHAMAN:Elemental": "ui/specs/shaman/elemental/apls/default.apl.json",
    "PRIEST:Shadow": "ui/specs/priest/dps/apls/default.apl.json",
    "DRUID:Balance": "ui/specs/druid/balance/apls/default.apl.json",
    # one Rogue list for every build: it checks which of Mutilate / Hemorrhage / Backstab the rogue has
    "ROGUE:Combat": "ui/specs/rogue/dps/apls/swords.apl.json",
    "ROGUE:Assassination": "ui/specs/rogue/dps/apls/swords.apl.json",
    "ROGUE:Subtlety": "ui/specs/rogue/dps/apls/swords.apl.json",
    "DRUID:Feral (Cat)": "ui/specs/druid/feralcat/apls/default.apl.json",
}


def lua(v, ind=""):
    if isinstance(v, dict):
        if not v:
            return "{}"
        parts = []
        for k, x in v.items():
            key = k if k.isidentifier() and k not in ("and", "or", "not", "end", "nil", "true", "false") else '["%s"]' % k
            parts.append("%s%s = %s" % (ind + "  ", key, lua(x, ind + "  ")))
        return "{\n" + ",\n".join(parts) + ",\n" + ind + "}"
    if isinstance(v, list):
        if not v:
            return "{}"
        return "{\n" + ",\n".join(ind + "  " + lua(x, ind + "  ") for x in v) + ",\n" + ind + "}"
    if isinstance(v, bool):
        return "true" if v else "false"
    if isinstance(v, (int, float)):
        return repr(v)
    return '"%s"' % str(v).replace("\\", "\\\\").replace('"', '\\"')


def main():
    lines = [
        'if DisasterZoneBoot and DisasterZoneBoot.Run("Data/SimAPL.lua", ...) then return end -- DisasterZone gear sim rotations.',
        "-- AUTO-GENERATED by gen_sim_apl.py - do not edit by hand; re-run the generator instead.",
        "-- Source: WoWSims TBC (github.com/wowsims/tbc-new, MIT) ui/specs/*/apls/*.apl.json, as Lua tables.",
        "local _, ns = ...",
        "ns.Data = ns.Data or {}",
        "ns.Data.SimAPL = {",
    ]
    first, aliases = {}, []
    for key, rel in APLS.items():
        if rel in first:
            aliases.append((key, first[rel]))  # the same list again: one table, two keys
            continue
        first[rel] = key
        with open(os.path.join(WOWSIMS, rel), encoding="utf-8") as f:
            apl = json.load(f)
        lines.append('  ["%s"] = %s,' % (key, lua(apl, "  ")))
    lines.append("}")
    for key, src in aliases:
        lines.append('ns.Data.SimAPL["%s"] = ns.Data.SimAPL["%s"]' % (key, src))
    with open(OUT, "wb") as f:
        f.write(("\n".join(lines) + "\n").encode("utf-8"))
    print("wrote", OUT)


if __name__ == "__main__":
    main()
